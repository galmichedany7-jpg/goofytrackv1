// Apex scenery: the landscape around the track (mountains, forests, rocks). Looks only.
//
// The game's mountains are a coarse ring of triangles that the physics also collides with.
// That original mesh is kept, untouched, for the physics (patch_bundle.js makes the game read it
// from mesh.userData.apexPhysics). What is drawn instead is rebuilt here from the same heights:
//
//   - the same hills, sampled several times finer and roughened with noise
//   - a second, taller range behind them for the skyline
//   - faces coloured by slope and altitude: grass, rock and snow caps in summer; snow, bare rock
//     and ice in winter; sand, banded red rock and pale summits in the desert
//   - pine forests on the foothills (summer, winter) or boulders (desert)
//   - Riviera (the mod's fourth environment): the same hills as a Mediterranean coast, maquis, limestone
//     and tan cliffs, villages with tiled roofs, umbrella pines and cypresses; on one side of the track the
//     hills drop to a beach lined with palm trees and the sea runs to the horizon, with yachts at anchor.
//     The game's own mountains are still what the physics collides with, under the sea too.
//
// Everything is one static mesh using the game's own mountain material, built when a track loads.
// The game calls into window.ApexScenery from the hooks added by patch_bundle.js.
(() => {
  'use strict';

  const RING = 100;                 // metres between two rings of the original mountains
  const RINGS = 7;                  // the original spans 7 rings
  const BACKDROP_RINGS = 9;         // extra range drawn behind them
  const MAX_TRIANGLES = 44000;      // budget for the terrain; props add at most ~16000
  const RIVIERA_GROUND = 6318394;   // 0x60693a, the plain's colour in the Riviera environment (patch_bundle.js sets it)
  const ENVIRONMENTS = { 3495480: 'summer', 11053224: 'winter', 11171394: 'desert', [RIVIERA_GROUND]: 'riviera' }; // by the game's ground colour

  // Display (sRGB) colours. `null` means "the game's ground colour", so slopes blend into the plain.
  const PALETTES = {
    summer: {
      ground: null, patch: 0.82, rock: [0.47, 0.45, 0.40], high: [0.60, 0.59, 0.56], snow: [0.93, 0.95, 0.98],
      foliage: [[0.13, 0.33, 0.18], [0.16, 0.38, 0.20], [0.20, 0.43, 0.22]], trunk: [0.30, 0.21, 0.14],
    },
    winter: {
      ground: null, patch: 0.94, rock: [0.40, 0.45, 0.55], high: [0.86, 0.90, 0.96], snow: [0.96, 0.98, 1.0],
      foliage: [[0.16, 0.30, 0.27], [0.19, 0.34, 0.30], [0.93, 0.96, 1.0]], trunk: [0.26, 0.20, 0.17],
    },
    desert: {
      ground: null, patch: 0.92, rock: [0.70, 0.41, 0.26], high: [0.84, 0.62, 0.42], snow: [0.92, 0.78, 0.58],
      strata: [[0.74, 0.44, 0.27], [0.62, 0.34, 0.22], [0.80, 0.52, 0.32]], boulder: [0.66, 0.44, 0.30],
    },
    riviera: {
      ground: null, patch: 0.88, rock: [0.58, 0.55, 0.49], high: [0.55, 0.53, 0.47], snow: [0.62, 0.60, 0.54],
      strata: [[0.60, 0.48, 0.36], [0.53, 0.42, 0.32], [0.64, 0.54, 0.42]], riviera: true,
      sea: [0.26, 0.48, 0.64], sand: [0.74, 0.67, 0.52], pine: [[0.20, 0.32, 0.16], [0.24, 0.36, 0.17]], cypress: [0.13, 0.24, 0.13],
      trunk: [0.42, 0.31, 0.22], walls: [[0.97, 0.92, 0.80], [0.95, 0.80, 0.70], [0.96, 0.88, 0.62], [0.99, 0.97, 0.93], [0.90, 0.72, 0.52]],
      tiles: [0.78, 0.40, 0.26], window: [0.25, 0.40, 0.62], hull: [0.97, 0.97, 0.97], deck: [0.80, 0.66, 0.48], frond: [0.34, 0.55, 0.25],
    },
  };

  // Riviera: the sea fills a wide bay on one side of the track (towards +z), the hills dropping to a beach
  const SEA_ANGLE = Math.PI / 2, SEA_HALF = 75 * Math.PI / 180, SEA_Y = 1.5;
  function Coast(radius) {
    const bay = angle => {
      const d = Math.abs(Math.atan2(Math.sin(angle - SEA_ANGLE), Math.cos(angle - SEA_ANGLE)));
      const t = Math.max(0, Math.min(1, (d - SEA_HALF * 0.65) / (SEA_HALF * 0.55)));
      return 1 - t * t * (3 - 2 * t);
    };
    // distance from the track's centre to the shore: close in the middle of the bay, receding to the headlands
    const shore = angle => { const b = bay(angle); return b < 0.03 ? Infinity : radius + 70 + (1 - b) * 1300 + 45 * (noise(Math.cos(angle) * 3 + 7, Math.sin(angle) * 3 + 2) - 0.5); };
    return {
      shore,
      isSea: (angle, rho) => rho > shore(angle),
      height: raw => (angle, rho) => {
        const s = shore(angle);
        if (rho > s) return SEA_Y;
        const b = bay(angle), h = raw(angle, rho) * (1 - 0.85 * b);
        if (s === Infinity) return h;
        const t = Math.max(0, Math.min(1, (rho - radius) / Math.max(1, s - radius))), ramp = (SEA_Y + 0.5) * t;   // up from the plain to the beach
        return Math.max(ramp, Math.min(h, ramp + (s - rho) * 0.32));
      },
    };
  }

  let current = null;               // { mesh, physics, hex }

  // Circuits that come with their own surroundings: the track part that marks them, and how to build them.
  // Monaco's town, harbour, sea and mountains are generated by apex-monaco.js from the circuit's centreline;
  // they replace the mountains drawn here. They are only drawn, never collided with.
  // Montbéliard's centre is drawn by apex-montbeliard.js from the real map carried by its json.
  const TOWNS = {
    240: { data: 'tracks/monaco.json', script: 'apex-monaco.js', builder: () => window.ApexMonaco },
    244: { data: 'tracks/montbeliard.json', script: 'apex-montbeliard.js', builder: () => window.ApexMontbeliard },
  };
  const PART_SIZE = 5;
  const PRELOAD_DELAY = 2500;       // ms after the game starts: the towns are built in the background, ready before they are needed
  const townData = new Map();       // url -> Promise of { terrain, objects }
  const townMeshes = new Map();     // url -> [terrain mesh, objects mesh], made once and kept for the next sessions
  let town = null;                  // { owner, files, origin, data, meshes }

  // A town takes a few seconds to generate: it is built in a worker, off the page's thread, so the game never
  // freezes; if workers are not available, on the page.
  function buildTown(files, circuit) {
    return new Promise((resolve, reject) => {
      const onPage = () => setTimeout(() => { try { resolve(files.builder().build(circuit)); } catch (e) { reject(e); } }, 0);
      let worker;
      try { worker = new Worker(files.script); } catch (e) { onPage(); return; }
      worker.onmessage = e => { worker.terminate(); if (e.data && e.data.town) resolve(e.data.town); else { console.warn('Apex: town worker failed, building on the page', e.data && e.data.error); onPage(); } };
      worker.onerror = e => { e.preventDefault && e.preventDefault(); worker.terminate(); onPage(); };
      worker.postMessage(circuit);
    });
  }
  function loadTown(files) {
    if (!townData.has(files.data)) townData.set(files.data, fetch(files.data).then(r => r.json()).then(circuit => buildTown(files, circuit)));
    return townData.get(files.data);
  }
  setTimeout(() => { for (const files of Object.values(TOWNS)) loadTown(files).catch(e => console.error('Apex: town scenery unavailable', e)); }, PRELOAD_DELAY);

  function removeTown() {
    if (town != null && town.meshes != null) for (const mesh of town.meshes) if (mesh.parent) mesh.parent.remove(mesh);   // kept for next time
    town = null;
    if (current != null) current.hex = -1;                               // bring the mountains back
  }

  // The material is a copy of the mountains' one (same lighting), coloured by the vertices only.
  function showTown() {
    if (town == null || town.data == null || current == null || current.mesh.parent == null) return;
    if (town.meshes == null && townMeshes.has(town.files.data)) town.meshes = townMeshes.get(town.files.data);
    if (town.meshes != null) {
      for (const mesh of town.meshes) {
        mesh.position.set(town.origin[0], town.origin[1], town.origin[2]);
        if (mesh.parent !== current.mesh.parent) current.mesh.parent.add(mesh);
      }
      return;
    }
    const Geometry = current.physics.constructor, Attribute = current.physics.attributes.position.constructor;
    town.meshes = [['terrain', false], ['objects', true]].map(([part, casts]) => {
      const material = current.mesh.material.clone();
      material.vertexColors = true;
      material.map = null;
      material.color.setRGB(1, 1, 1);
      if (window.ApexGfx) window.ApexGfx.registerMaterial(material);
      const geometry = new Geometry();
      geometry.setAttribute('position', new Attribute(town.data[part].positions, 3));
      geometry.setAttribute('color', new Attribute(town.data[part].colors, 3));
      if (town.data[part].normals) geometry.setAttribute('normal', new Attribute(town.data[part].normals, 3));
      else geometry.computeVertexNormals();
      const mesh = new current.mesh.constructor(geometry, material);
      mesh.position.set(town.origin[0], town.origin[1], town.origin[2]);
      mesh.receiveShadow = true;
      mesh.castShadow = casts;                                           // buildings, the tunnel and the stands shade the road
      current.mesh.parent.add(mesh);
      return mesh;
    });
    townMeshes.set(town.files.data, town.meshes);
  }

  // ------------------------------------------------------------------ small maths
  const hash2 = (x, y) => { const s = Math.sin(x * 127.1 + y * 311.7) * 43758.5453123; return s - Math.floor(s); };
  function noise(x, y) {
    const xi = Math.floor(x), yi = Math.floor(y), xf = x - xi, yf = y - yi;
    const u = xf * xf * (3 - 2 * xf), v = yf * yf * (3 - 2 * yf);
    const a = hash2(xi, yi), b = hash2(xi + 1, yi), c = hash2(xi, yi + 1), d = hash2(xi + 1, yi + 1);
    return a + (b - a) * u + (c - a) * v + (a - b - c + d) * u * v;
  }
  const fbm = (x, y) => noise(x, y) * 0.55 + noise(x * 2.1 + 5.2, y * 2.1 + 1.3) * 0.30 + noise(x * 4.3 + 9.1, y * 4.3 + 7.7) * 0.15;
  const ridged = (x, y) => { const n = 1 - Math.abs(2 * fbm(x, y) - 1); return n * n; };
  const catmull = (p0, p1, p2, p3, t) => 0.5 * ((2 * p1) + (-p0 + p2) * t + (2 * p0 - 5 * p1 + 4 * p2 - p3) * t * t + (-p0 + 3 * p1 - 3 * p2 + p3) * t * t * t);
  function random(seed) {           // small deterministic generator: the same track always gets the same forest
    let a = seed >>> 0;
    return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; };
  }
  const toLinear = c => Math.pow(c, 2.2);

  // ------------------------------------------------------------------ the original heights
  // The game's mesh is a polar grid: `sectors` slices around the track, RINGS rings of quads, 6 vertices per quad.
  function readOriginal(geometry) {
    const p = geometry.attributes.position.array;
    const quads = p.length / 18;
    const sectors = Math.round(quads / RINGS);
    if (sectors < 3 || sectors * RINGS !== quads) return null;
    const H = [];
    for (let e = 0; e < sectors; e++) {
      const row = [];
      for (let k = 0; k < RINGS; k++) row.push(p[(e * RINGS + k) * 18 + 1]);
      row.push(p[(e * RINGS + RINGS - 1) * 18 + 5 * 3 + 1]);
      H.push(row);
    }
    return { sectors, H, radius: Math.hypot(p[0], p[2]) };
  }

  function heightField(original) {
    const { sectors, H, radius } = original;
    const at = (e, k) => H[((e % sectors) + sectors) % sectors][Math.max(0, Math.min(RINGS, k))];
    // skyline: a few broad summits around the horizon
    const summit = angle => 0.35 + 0.65 * noise(Math.cos(angle) * 2.3 + 11, Math.sin(angle) * 2.3 + 4);
    return (angle, rho) => {
      const x = Math.cos(angle) * rho, z = Math.sin(angle) * rho;
      const v = (rho - radius) / RING;
      if (v <= 0) return 0;
      if (v < RINGS) {
        const u = angle / (2 * Math.PI) * sectors, e = Math.floor(u), k = Math.floor(v), tu = u - e, tv = v - k;
        const col = j => catmull(at(e - 1, k + j), at(e, k + j), at(e + 1, k + j), at(e + 2, k + j), tu);
        const base = Math.max(0, catmull(col(-1), col(0), col(1), col(2), tv));
        const rough = (fbm(x / 70, z / 70) - 0.5) * 0.7 + (fbm(x / 23, z / 23) - 0.5) * 0.25;
        return Math.max(0, base * (1 + rough) + Math.min(1, base / 25) * (ridged(x / 110, z / 110) - 0.35) * 14) * Math.min(1, v * 3);
      }
      const w = (v - RINGS) / BACKDROP_RINGS;                    // 0..1 across the far range
      if (w >= 1) return 0;
      const bump = Math.pow(Math.sin(Math.PI * w), 0.8);
      return bump * summit(angle) * (150 + 190 * ridged(x / 330, z / 330)) * (0.75 + 0.5 * fbm(x / 120, z / 120));
    };
  }

  // ------------------------------------------------------------------ building the mesh
  function build(original, environment, base) {
    const palette = PALETTES[environment];
    const { sectors, radius } = original;
    const coast = palette.riviera ? Coast(radius) : null;
    const height = coast ? coast.height(heightField(original)) : heightField(original);
    const positions = [], colors = [];
    const tint = c => (c == null ? [1, 1, 1] : [toLinear(c[0]) / base.r, toLinear(c[1]) / base.g, toLinear(c[2]) / base.b]);
    const tri = (a, b, c, color, shade) => {
      positions.push(a[0], a[1], a[2], b[0], b[1], b[2], c[0], c[1], c[2]);
      for (let i = 0; i < 3; i++) colors.push(color[0] * shade, color[1] * shade, color[2] * shade);
    };

    // radial rows: fine across the original hills, coarser across the far range
    const rows = [];
    for (let i = 0; i <= RINGS * 3; i++) rows.push(radius + i * RING / 3);
    for (let i = 1; i <= 12; i++) rows.push(radius + RINGS * RING + i * BACKDROP_RINGS * RING / 12);
    if (coast) for (const far of [3000, 6000, 12000]) rows.push(radius + far);   // the sea, out to the horizon
    const strips = rows.length - 1;
    let columns = sectors * Math.max(3, Math.min(8, Math.ceil(170 / sectors)));
    columns = Math.max(sectors, Math.min(columns, Math.floor(MAX_TRIANGLES / (strips * 2))));

    const grid = [];
    for (let i = 0; i <= columns; i++) {
      const angle = (i % columns) / columns * 2 * Math.PI, line = [];
      for (const rho of rows) line.push([Math.cos(angle) * rho, height(angle, rho), Math.sin(angle) * rho]);
      grid.push(line);
    }
    const terrainColor = (a, b, c) => {
      const y = (a[1] + b[1] + c[1]) / 3, cx = (a[0] + b[0] + c[0]) / 3, cz = (a[2] + b[2] + c[2]) / 3;
      const ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2], vx = c[0] - a[0], vy = c[1] - a[1], vz = c[2] - a[2];
      const nx = uy * vz - uz * vy, ny = uz * vx - ux * vz, nz = ux * vy - uy * vx;
      const flat = Math.abs(ny) / (Math.hypot(nx, ny, nz) || 1);  // 1 = level ground, 0 = cliff
      const shade = 0.94 + 0.12 * hash2(cx * 0.37, cz * 0.37);
      if (coast) {
        const angle = Math.atan2(cz, cx), rho = Math.hypot(cx, cz), s = coast.shore(angle);
        if (rho > s) return [tint(palette.sea), 0.97 + 0.06 * hash2(cx * 0.01, cz * 0.01)];
        if (rho > s - 22 && y < SEA_Y + 3) return [tint(palette.sand), shade];
      }
      if (y > 185 && flat > 0.5) return [tint(palette.snow), shade];
      if (y > 120) return [tint(flat > 0.62 ? palette.high : palette.rock), shade];
      if (flat < 0.80 && y > 6) {
        if (palette.strata) return [tint(palette.strata[Math.abs(Math.floor(y / 11)) % palette.strata.length]), shade];
        return [tint(palette.rock), shade];
      }
      return [tint(null), shade * (fbm(cx / 85, cz / 85) > 0.58 ? palette.patch : 1)];
    };
    for (let i = 0; i < columns; i++) for (let j = 0; j < strips; j++) {
      const a = grid[i][j], b = grid[i + 1][j], c = grid[i + 1][j + 1], d = grid[i][j + 1];
      if (a[1] === 0 && b[1] === 0 && c[1] === 0 && d[1] === 0 && j > RINGS * 3) continue; // flat beyond the range: nothing to draw
      if (coast && j > RINGS * 3 && [a, b, c, d].every(p => p[1] === 0)) continue;
      // alternate the diagonal so the facets do not line up
      const quad = (i + j) % 2 === 0 ? [[a, b, c], [a, c, d]] : [[a, b, d], [b, c, d]];
      for (const t of quad) { const [color, shade] = terrainColor(...t); tri(t[0], t[1], t[2], color, shade); }
    }

    // props on the foothills, never closer to the track than the edge of the plain around it
    const rnd = random(sectors * 7919 + Math.round(radius));
    const place = (count, add) => {
      for (let n = 0, tries = 0; n < count && tries < count * 12; tries++) {
        const angle = rnd() * 2 * Math.PI, rho = radius - 95 + Math.pow(rnd(), 1.3) * 560;
        const x = Math.cos(angle) * rho, z = Math.sin(angle) * rho, y = height(angle, rho);
        if (y > 80 || Math.abs(height(angle, rho + 7) - y) > 5.5 || fbm(x / 95 + 3, z / 95 + 8) < 0.46) continue;
        add(x, y - 0.3, z, rnd);
        n++;
      }
    };
    if (palette.riviera) riviera(palette, coast, height, radius, rnd, place, tint, tri);
    else if (palette.foliage) {
      const foliage = palette.foliage.map(tint), trunk = tint(palette.trunk);
      place(Math.max(220, Math.min(600, Math.round(radius * 0.7))), (x, y, z, r) => {
        const s = 0.8 + r() * 0.75, turn = r() * Math.PI, shade = 0.88 + r() * 0.24;
        const ring = (radiusAt, yAt, sides) => Array.from({ length: sides }, (_, i) => {
          const a = turn + i / sides * 2 * Math.PI;
          return [x + Math.cos(a) * radiusAt * s, y + yAt * s, z + Math.sin(a) * radiusAt * s];
        });
        const bottom = ring(0.45, 0, 4), top = ring(0.45, 2.4, 4);
        for (let i = 0; i < 4; i++) { const k = (i + 1) % 4; tri(bottom[i], top[i], top[k], trunk, shade); tri(bottom[i], top[k], bottom[k], trunk, shade); }
        [[3.0, 2.0, 6.2], [2.3, 4.7, 8.8], [1.5, 7.3, 11.2]].forEach(([rad, from, to], tier) => {
          const rim = ring(rad, from, 6), tip = [x, y + to * s, z];
          for (let i = 0; i < 6; i++) tri(rim[i], tip, rim[(i + 1) % 6], foliage[tier], shade * (0.9 + 0.2 * (i % 2)));
        });
      });
    } else {
      const boulder = tint(palette.boulder);
      place(240, (x, y, z, r) => {
        const sx = 2 + r() * 5, sy = 1.2 + r() * 3.5, sz = 2 + r() * 5, turn = r() * Math.PI;
        const pt = (a, up, k) => [x + Math.cos(turn + a) * sx * k, y + up * sy, z + Math.sin(turn + a) * sz * k];
        const rim = [0, 1, 2, 3].map(i => pt(i * Math.PI / 2 + r() * 0.5, 0.25 + r() * 0.3, 0.8 + r() * 0.4));
        const top = pt(0, 1, 0), bottom = pt(0, -0.4, 0);
        for (let i = 0; i < 4; i++) { tri(rim[i], top, rim[(i + 1) % 4], boulder, 0.85 + r() * 0.3); tri(rim[i], rim[(i + 1) % 4], bottom, boulder, 0.7); }
      });
    }
    return { positions: new Float32Array(positions), colors: new Float32Array(colors) };
  }

  // ------------------------------------------------------------------ Riviera props
  function riviera(palette, coast, height, radius, rnd, place, tint, tri) {
    const quad = (a, b, c, d, col, shade) => { tri(a, b, c, col, shade); tri(a, c, d, col, shade); };
    const box = (x, z, y0, y1, hw, hd, turn, col, shade = 1) => {         // a block standing on y0, turned by `turn`
      const ca = Math.cos(turn), sa = Math.sin(turn);
      const p = (u, v, y) => [x + u * ca - v * sa, y, z + u * sa + v * ca];
      const c = [[-hw, -hd], [hw, -hd], [hw, hd], [-hw, hd]];
      for (let i = 0; i < 4; i++) { const [u0, v0] = c[i], [u1, v1] = c[(i + 1) % 4]; quad(p(u0, v0, y0), p(u0, v0, y1), p(u1, v1, y1), p(u1, v1, y0), col, shade * (i % 2 ? 0.9 : 1)); }
      return { p, c };
    };
    const ok = (angle, rho, size) => {                                 // dry, gentle ground
      if (coast.isSea(angle, rho + size) || coast.isSea(angle, rho - size)) return null;
      const y = height(angle, rho), dy = Math.max(Math.abs(height(angle + size / rho, rho) - y), Math.abs(height(angle, rho + size) - y));
      return dy > size * 0.45 ? null : y;
    };
    // villages: pastel houses with tiled roofs, clustered on the gentle slopes
    const walls = palette.walls.map(tint), tiles = tint(palette.tiles), windowCol = tint(palette.window);
    for (let v = 0; v < 9; v++) {
      const va = rnd() * 2 * Math.PI, vr = radius + 60 + rnd() * 520;
      for (let k = 0; k < 34; k++) {
        const angle = va + (rnd() - 0.5) * 140 / vr, rho = vr + (rnd() - 0.5) * 140, y = ok(angle, rho, 9);
        if (y == null || y > 120) continue;
        const x = Math.cos(angle) * rho, z = Math.sin(angle) * rho, hw = 3 + rnd() * 3, hd = 3 + rnd() * 2.5, top = y + 4 + Math.floor(rnd() * 3) * 3, turn = rnd() * Math.PI;
        const { p, c } = box(x, z, y - 3, top, hw, hd, turn, walls[Math.floor(rnd() * walls.length)], 0.95 + rnd() * 0.1);
        for (let i = 0; i < 4; i += 2) {                                 // a row of windows on the long sides
          const [u0, v0] = c[i], [u1, v1] = c[(i + 1) % 4], e = 1.03;
          quad(p(u0 * e + (u1 - u0) * 0.2, v0 * e, top - 2.6), p(u0 * e + (u1 - u0) * 0.2, v0 * e, top - 1.4), p(u1 * e - (u1 - u0) * 0.2, v1 * e, top - 1.4), p(u1 * e - (u1 - u0) * 0.2, v1 * e, top - 2.6), windowCol, 1);
        }
        const peak = p(0, 0, top + Math.min(hw, hd) * 0.6);
        for (let i = 0; i < 4; i++) { const [u0, v0] = c[i], [u1, v1] = c[(i + 1) % 4]; tri(p(u0 * 1.08, v0 * 1.08, top), p(u1 * 1.08, v1 * 1.08, top), peak, tiles, i % 2 ? 0.86 : 1); }
      }
    }
    // umbrella pines and cypresses on the hills
    const pine = palette.pine.map(tint), cypress = tint(palette.cypress), trunk = tint(palette.trunk);
    place(Math.max(260, Math.min(700, Math.round(radius * 0.8))), (x, y, z, r) => {
      if (coast.isSea(Math.atan2(z, x), Math.hypot(x, z) + 8)) return;
      const s = 0.8 + r() * 0.7, shade = 0.88 + r() * 0.24;
      if (r() < 0.35) {                                                  // cypress: tall and narrow
        const h = (9 + r() * 5) * s, rim = Array.from({ length: 6 }, (_, i) => [x + Math.cos(i / 6 * 2 * Math.PI) * 1.6 * s, y + h * 0.3, z + Math.sin(i / 6 * 2 * Math.PI) * 1.6 * s]);
        for (let i = 0; i < 6; i++) { tri(rim[i], [x, y + h, z], rim[(i + 1) % 6], cypress, shade * (0.9 + 0.2 * (i % 2))); tri(rim[i], rim[(i + 1) % 6], [x, y, z], cypress, shade * 0.8); }
        return;
      }
      box(x, z, y, y + 5.5 * s, 0.35 * s, 0.35 * s, r(), trunk, shade);  // umbrella pine: a flat, wide crown
      const col = pine[Math.floor(r() * pine.length)], cy = y + 6 * s, rim = Array.from({ length: 7 }, (_, i) => [x + Math.cos(i / 7 * 2 * Math.PI) * 4.5 * s, cy, z + Math.sin(i / 7 * 2 * Math.PI) * 4.5 * s]);
      for (let i = 0; i < 7; i++) { tri(rim[i], [x, cy + 1.8 * s, z], rim[(i + 1) % 7], col, shade * (0.92 + 0.16 * (i % 2))); tri(rim[i], rim[(i + 1) % 7], [x, cy - 1.2 * s, z], col, shade * 0.75); }
    });
    // palm trees along the beach, yachts at anchor
    const frond = tint(palette.frond), hull = tint(palette.hull), deck = tint(palette.deck);
    for (let k = 0; k < 140; k++) {
      const angle = SEA_ANGLE + (rnd() - 0.5) * 2 * SEA_HALF * 0.9, s = coast.shore(angle);
      if (s === Infinity) continue;
      const rho = s - 9 - rnd() * 10, x = Math.cos(angle) * rho, z = Math.sin(angle) * rho, y = height(angle, rho) - 0.3, h = 7 + rnd() * 4;
      box(x, z, y, y + h, 0.25, 0.25, rnd(), trunk, 0.9);
      for (let i = 0; i < 6; i++) {
        const a = i / 6 * 2 * Math.PI + rnd(), tip = [x + Math.cos(a) * 3.6, y + h - 1.4, z + Math.sin(a) * 3.6], w = [-Math.sin(a) * 0.7, Math.cos(a) * 0.7];
        tri([x, y + h + 0.3, z], [tip[0] + w[0], tip[1] + 1, tip[2] + w[1]], tip, frond, 1);
        tri([x, y + h + 0.3, z], tip, [tip[0] - w[0], tip[1] + 1, tip[2] - w[1]], frond, 0.85);
      }
    }
    for (let k = 0; k < 40; k++) {
      const angle = SEA_ANGLE + (rnd() - 0.5) * 2 * SEA_HALF * 0.8, s = coast.shore(angle);
      if (s === Infinity) continue;
      const rho = s + 60 + rnd() * 1100, x = Math.cos(angle) * rho, z = Math.sin(angle) * rho, L = 14 + rnd() * 30, turn = rnd() * Math.PI;
      const { p } = box(x, z, SEA_Y - 0.5, SEA_Y + 1.6 + L * 0.03, L / 2, L * 0.13, turn, hull);
      quad(p(-L / 2, -L * 0.13, SEA_Y + 1.6 + L * 0.03), p(L / 2, -L * 0.13, SEA_Y + 1.6 + L * 0.03), p(L / 2, L * 0.13, SEA_Y + 1.6 + L * 0.03), p(-L / 2, L * 0.13, SEA_Y + 1.6 + L * 0.03), deck, 1);
      tri(p(L / 2, -L * 0.13, SEA_Y + 1.6 + L * 0.03), p(L * 0.7, 0, SEA_Y + 1.6 + L * 0.03), p(L / 2, L * 0.13, SEA_Y + 1.6 + L * 0.03), deck, 1);   // the bow
      box(x - Math.cos(turn) * L * 0.08, z - Math.sin(turn) * L * 0.08, SEA_Y + 1.6 + L * 0.03, SEA_Y + 3.6 + L * 0.05, L * 0.22, L * 0.09, turn, hull, 1.05);
    }
  }

  function rebuild() {
    const { mesh, physics } = current;
    const material = mesh.material;
    const hex = material.color.getHex();
    current.hex = hex;
    if (town != null) {                                                  // the town's own landscape replaces the mountains
      if (mesh.geometry !== physics) mesh.geometry.dispose();
      mesh.geometry = new physics.constructor();
      return;
    }
    const original = readOriginal(physics);
    if (original == null) return;
    const data = build(original, ENVIRONMENTS[hex] || 'summer', material.color);
    const Geometry = physics.constructor, Attribute = physics.attributes.position.constructor;
    const geometry = new Geometry();
    geometry.setAttribute('position', new Attribute(data.positions, 3));
    geometry.setAttribute('color', new Attribute(data.colors, 3));
    geometry.computeVertexNormals();
    if (mesh.geometry !== physics) mesh.geometry.dispose();
    mesh.geometry = geometry;
    if (!material.vertexColors) { material.vertexColors = true; material.needsUpdate = true; }
  }

  window.ApexScenery = {
    // Read-only snapshot for the console
    debug: () => current && { triangles: current.mesh.geometry.attributes.position.count / 3, physicsVertices: current.physics.attributes.position.count, environment: ENVIRONMENTS[current.hex] },

    // The game just created its mountain mesh
    mountains(mesh) {
      current = null;
      try {
        if (mesh.geometry.attributes.position.count === 0) return;       // very large tracks have no mountains
        mesh.userData.apexPhysics = mesh.geometry;                        // what the physics keeps reading
        current = { mesh, physics: mesh.geometry, hex: -1 };
        rebuild();
      } catch (e) {
        console.error('Apex: scenery unavailable, keeping the original mountains', e);
        if (current != null) { mesh.geometry = current.physics; current = null; }
      }
    },

    // A track is being played: does it bring its own town?
    track(owner, track) {
      removeTown();
      try {
        let found = null;
        track.getTrackData().forEachPart((x, y, z, id) => { if (TOWNS[id] != null && found == null) found = { files: TOWNS[id], origin: [x * PART_SIZE, y * PART_SIZE, z * PART_SIZE] }; });
        if (found == null) return;
        const mine = town = { owner, files: found.files, origin: found.origin, data: null, meshes: null };
        if (current != null) current.hex = -1;                           // hide the mountains on the next frame
        loadTown(found.files).then(data => { if (town === mine) mine.data = data; }).catch(e => console.error('Apex: town scenery unavailable', e));
      } catch (e) { console.error('Apex: town scenery unavailable', e); }
    },
    trackEnd(owner) {
      if (town != null && town.owner === owner) removeTown();
    },

    // Each frame: the ground colour tells which environment is shown; recolour and replant when it changes
    frame() {
      try { showTown(); } catch (e) { console.error('Apex: town scenery failed', e); removeTown(); }
      if (current == null) return;
      if (current.mesh.parent == null) { current = null; return; }        // mountains were cleared
      if (current.mesh.material.color.getHex() !== current.hex) {
        try { rebuild(); } catch (e) { console.error('Apex: scenery rebuild failed', e); current = null; }
      }
    },
  };
})();
